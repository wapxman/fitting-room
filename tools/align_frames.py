# -*- coding: utf-8 -*-
"""Привести кадры оборота к одной «камере».

Зачем. Модель рисует каждый ракурс заново, и человек каждый раз немного другого
размера и не в той же точке кадра. При прокрутке это читается как прыжки: рост
скачет, фигура ездит влево-вправо. Настоящий 360-вьюер требует, чтобы менялся
ТОЛЬКО ракурс.

Что делает: находит рамку фигуры на сером фоне, масштабирует так, чтобы рост
занимал одну и ту же долю кадра, ставит по центру и на общую линию пола.

⚠️ РАМКА ИЩЕТСЯ ПО ПРОЕКЦИЯМ, А НЕ ПОИСКОМ СВЯЗНЫХ ОБЛАСТЕЙ. Два захода через
связность провалились, и оба раза молча:
  — «взять самую большую область»: по периметру кадра идёт кромка (JPEG-звон и
    виньетка), она СОМКНУТА в кольцо и оказывается больше человека. Рамка
    выходила во весь кадр (0…1447), а замеры снимались с пустого фона;
  — «взять самую большую, не касающуюся края»: человек краем кадра как раз
    касается (стопы и макушка у границы), его область отбрасывалась, и
    выбирались крапины в 25–88 пикселей, после чего масштаб улетал в космос и
    PIL падал с MemoryError.
Проекция свободна от обеих бед: кольцо кромки даёт 1–2 пикселя на строку и не
проходит порог, а фигура даёт сотни.
"""
import os
import sys

import numpy as np
from PIL import Image

SRC = sys.argv[1] if len(sys.argv) > 1 else "frames"
DST = sys.argv[2] if len(sys.argv) > 2 else "frames_aligned"
os.makedirs(DST, exist_ok=True)

OUT_W, OUT_H = 900, 1200
BODY_FRAC = 0.90          # какую долю высоты холста занимает фигура
BASELINE = 0.972          # где стоят подошвы (доля высоты холста)
ROW_MIN = 0.012           # доля ширины: сколько «не-фона» в строке считать телом
COL_MIN = 0.020           # доля высоты для столбца


def bbox(a, T=20.0):
    """Рамка фигуры: (x0, y0, x1, y1, доля_строк_с_телом, порог).

    ⚠️ Фон сравнивается с медианой СВОЕЙ ЖЕ строки (и своего столбца), а не с
    общей моделью подложки. Так сделано потому, что у кадров есть виньетка:
    линейная рампа слева-направо её не описывает, и в пустом небе над головой
    «отклонение от фона» выходило большим — рамка получалась во весь кадр
    (рост 100 % кадра на всех ракурсах). Медиана строки自 подстраивается под
    любой плавный перепад: в пустой строке почти все пиксели равны медиане,
    в строке с человеком — десятки процентов от неё далеки.
    """
    H, W, _ = a.shape
    rowmed = np.median(a, axis=1)                        # (H,3)
    drow = np.abs(a - rowmed[:, None, :]).sum(axis=2)
    mask = drow > T

    # Столбцы берём из ЭТОЙ ЖЕ построчной маски, а не из медианы столбца.
    # Медиана столбца ломается ровно так же, как ломалась рампа, только по
    # другой оси: у подложки есть вертикальный перепад, пиксели столбца сильно
    # отличаются от его медианы даже в пустом поле — и ширина выходила во весь
    # кадр (1086 из 1086) при уже правильной высоте.
    rowfrac = mask.mean(axis=1)
    colfrac = mask.mean(axis=0)

    ri = np.where(rowfrac > 0.030)[0]
    ci = np.where(colfrac > 0.020)[0]
    if len(ri) == 0 or len(ci) == 0:
        return None
    return int(ci[0]), int(ri[0]), int(ci[-1]), int(ri[-1]), float(rowfrac.mean()), T


# Кадры лежат по подкаталогам сочетаний (frames/<сочетание>/aNNN.png), поэтому
# обходим дерево и сохраняем относительный путь — иначе кадры разных комплектов
# перезаписали бы друг друга, ведь имена ракурсов у всех одинаковые.
files = []
for d, _, fs in os.walk(SRC):
    for f in fs:
        if f.lower().endswith(".png"):
            files.append(os.path.relpath(os.path.join(d, f), SRC).replace("\\", "/"))
files.sort()
if not files:
    print("кадров нет")
    sys.exit(1)

found, greys = {}, []
for f in files:
    im = Image.open(os.path.join(SRC, f)).convert("RGB")
    a = np.asarray(im).astype(np.float32)
    b = bbox(a)
    if b is None:
        print(f"  {f}: фигура не найдена, пропуск")
        continue
    x0, y0, x1, y1, frac, tol = b
    h, w = y1 - y0 + 1, x1 - x0 + 1
    # Санитарная проверка: человек в полный рост занимает большую часть кадра.
    if h < 0.45 * im.height:
        print(f"  {f}: рамка подозрительно мала ({h} px из {im.height}), пропуск")
        continue
    found[f] = (im, (x0, y0, x1, y1))
    greys.append(np.median(a[:, :40, :].reshape(-1, 3), axis=0))
    print(f"  {f}: рост {h} px ({h/im.height:.0%} кадра), ширина {w}, "
          f"не-фон {frac:.0%}, порог {tol}")

if not found:
    print("ни одного пригодного кадра")
    sys.exit(1)

grey = tuple(int(v) for v in np.median(np.array(greys), axis=0))
print("серый холста:", grey)

for f, (im, (x0, y0, x1, y1)) in found.items():
    k = (OUT_H * BODY_FRAC) / (y1 - y0 + 1)
    big = im.resize((max(1, round(im.width * k)), max(1, round(im.height * k))), Image.LANCZOS)
    canvas = Image.new("RGB", (OUT_W, OUT_H), grey)
    canvas.paste(big, (round(OUT_W / 2 - (x0 + x1) / 2 * k),
                       round(OUT_H * BASELINE - y1 * k)))
    dst_path = os.path.join(DST, f)
    os.makedirs(os.path.dirname(dst_path), exist_ok=True)
    canvas.save(dst_path)

print(f"\nвыровнено: {len(found)} кадр(ов) в {DST}")
