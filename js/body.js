// Построение фигуры. Отдельным файлом, потому что это самая содержательная
// часть: из профилей сечений собирается тело, а из тех же профилей с припуском —
// одежда. Благодаря общему источнику одежда садится по телу, а не «висит рядом».
import * as THREE from 'three';

// ─────────────────────────────────────────────────────────────────────────────
// ⚠️ ПОЧЕМУ ЗДЕСЬ НЕ ЧИСТЫЕ ЗАМЕРЫ С ФОТО, А СВЕРКА С АНАТОМИЕЙ
//
// Первая версия брала цифры из tools/analyze_photo.py как есть, и фигура вышла
// бочкой БЕЗ РУК. Разбор: ширина плеч с фронтального кадра меряется на уровне,
// где к корпусу ПРИЖАТЫ РУКИ, поэтому замер дал 0,298 роста вместо реальной
// биакромиальной ширины ~0,245. Торс раздулся до полуширины 0,26 м, точки
// крепления рук оказались на 0,217 м — то есть ВНУТРИ торса, и руки просто
// исчезли в нём. Похожая беда с «пахом»: детектор дал 0,56 роста от макушки,
// ноги вышли 0,385 роста вместо нормальных ~0,47, фигура стала приземистой.
//
// Поэтому: с фото берём ОТНОШЕНИЯ, которым можно верить (талия/плечи 0,746,
// бёдра/плечи 0,734 — они близки к типовым 0,67 и 0,78, то есть телосложение
// обычное), а абсолютные уровни и ширины — анатомические. Цвета с фото точные.
// ─────────────────────────────────────────────────────────────────────────────
export const M = {
  heightM: 1.78,
  // Доли РОСТА, считая от макушки вниз.
  level: { chin: 0.133, shoulder: 0.185, chest: 0.26, waist: 0.33, hip: 0.46, crotch: 0.48,
           knee: 0.72, ankle: 0.955 },
  // Полная ширина (не радиус) в долях роста.
  //
  // ⚠️ ВТОРАЯ ОШИБКА, ИСПРАВЛЕННАЯ ЗДЕСЬ: грудь стояла 0,232 роста, то есть
  // почти вровень с плечами (0,250) — отсюда «бочка». У человека ширина
  // ГРУДНОЙ КЛЕТКИ заметно меньше размаха плеч: плечи широкие за счёт дельт,
  // а дельты в этой модели — верхушки РУК, а не торса. Поэтому торс узкий
  // (грудь 0,186), а нужные 0,25 набираются торсом вместе с руками по бокам.
  width: { head: 0.125, neck: 0.068, shoulder: 0.250, chest: 0.186, waist: 0.160, hip: 0.192 },
  color: { hair: 0x1d1d1b, skin: 0xe8b79e },
  // Замеренное с фото — оставлено для панели и как след происхождения цифр.
  measured: { shoulderToHeight: 0.298, waistToShoulder: 0.746, hipToShoulder: 0.734 },
};

/** Кусок тела вращения с переменным радиусом.
 *
 * Почему не цилиндр и не капсула: у человека нет ни одного участка постоянного
 * радиуса. Берём цилиндр с большим числом сегментов по высоте и двигаем вершины
 * радиально по функции профиля — получается гладкая форма, и та же функция с
 * припуском даёт одежду поверх.
 *
 * @param {(t:number)=>[number,number]} profile t:0..1 сверху вниз -> [rx, rz] в МЕТРАХ
 */
export function limb(profile, h, segH = 48, segR = 28) {
  const g = new THREE.CylinderGeometry(1, 1, h, segR, segH, true);
  const p = g.attributes.position;
  const v = new THREE.Vector3();
  for (let i = 0; i < p.count; i++) {
    v.fromBufferAttribute(p, i);
    const t = Math.min(1, Math.max(0, 1 - (v.y / h + 0.5)));
    const [rx, rz] = profile(t);
    const a = Math.atan2(v.z, v.x);
    p.setX(i, Math.cos(a) * rx);
    p.setZ(i, Math.sin(a) * rz);
  }
  g.computeVertexNormals();
  return g;
}

/** Купол для торца конечности, чтобы не зияла дыра. up=true — вверх. */
export function cap(rx, rz, ry, up = true) {
  const g = new THREE.SphereGeometry(1, 28, 16, 0, Math.PI * 2,
                                     up ? 0 : Math.PI / 2, Math.PI / 2);
  g.scale(rx, ry, rz);
  return g;
}

const lerp = (a, b, t) => a + (b - a) * t;
export const smooth = (t, a, b) => {
  if (t <= a) return 0;
  if (t >= b) return 1;
  const x = (t - a) / (b - a);
  return x * x * (3 - 2 * x);
};

/**
 * Профиль ТОРСА от основания шеи (t=0) до паха (t=1), радиусы в метрах.
 * Сечение эллиптическое: грудная клетка глубже, чем узкая со спины.
 */
export function torsoProfile(H, pad = 0) {
  const ch = M.width.chest / 2 * H;      // 0,093H — самая широкая часть ТОРСА
  const wa = M.width.waist / 2 * H;
  const hp = M.width.hip / 2 * H;
  const tr = ch * 0.76;                  // трапеции у основания шеи
  return (t) => {
    let rx;
    if (t < 0.14)      rx = lerp(tr, ch * 1.03, smooth(t, 0, 0.14));      // шея→верх груди
    else if (t < 0.38) rx = lerp(ch * 1.03, ch, smooth(t, 0.14, 0.38));   // грудь
    else if (t < 0.66) rx = lerp(ch, wa, smooth(t, 0.38, 0.66));          // грудь→талия
    else               rx = lerp(wa, hp, smooth(t, 0.66, 1));             // талия→бёдра
    // Глубина меньше ширины и растёт книзу: грудная клетка плоская спереди-сзади
    // относительно своей ширины, таз — наоборот. Прежние 0,80…0,94 раздували
    // корпус в профиль почти до круга.
    const depth = lerp(0.64, 0.82, smooth(t, 0.1, 0.9));
    return [rx + pad, rx * depth + pad];
  };
}

/** Рука: дельта → локоть → запястье, радиусы в метрах. */
export function armProfile(H, pad = 0) {
  const r0 = 0.0290 * H, r1 = 0.0215 * H, r2 = 0.0150 * H;
  return (t) => {
    const r = t < 0.5 ? lerp(r0, r1, smooth(t, 0, 0.5)) : lerp(r1, r2, smooth(t, 0.5, 1));
    return [r + pad, r * 0.90 + pad];
  };
}

/** Нога: бедро → колено → щиколотка, радиусы в метрах. */
export function legProfile(H, pad = 0) {
  const r0 = 0.0460 * H, r1 = 0.0310 * H, r2 = 0.0200 * H;
  return (t) => {
    // Икра: лёгкое утолщение сразу под коленом, иначе нога читается палкой.
    const calf = 1 + 0.13 * Math.exp(-Math.pow((t - 0.70) / 0.12, 2));
    const r = (t < 0.55 ? lerp(r0, r1, smooth(t, 0, 0.55))
                        : lerp(r1, r2, smooth(t, 0.55, 1))) * calf;
    return [r + pad, r * 0.94 + pad];
  };
}
